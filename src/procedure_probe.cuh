constexpr Word branches=193,utterance=1536;
struct Branch {Half left,right,remaining;Byte type;};
struct Tree {
    Branch cell[branches];Summary meaning[branches];Word n=0;
};
AX_FN void grow(Tree &t,const Convention &v,Word seed,Word budget,Word shape) {
    t.n=1;t.cell[0]={0,0,static_cast<Half>(budget),0};
    for (Word j=0;j<t.n;++j) {
        auto &b=t.cell[j];Word key=mix(seed^(j+1)*0x9e3779b9u);
        if (!b.remaining) {b.type=static_cast<Byte>(key%actions);continue;}
        Word op=key%verbs;b.type=static_cast<Byte>(actions+op);
        Word remaining=b.remaining-1,left=remaining;
        if (v.arity[op]==2) left=shape==0 ? ((key&32768) ? remaining : 0) : shape==1 ? remaining/2 : (key>>8)%(remaining+1);
        b.left=static_cast<Half>(t.n);t.cell[t.n++]={0,0,static_cast<Half>(left),0};
        if (v.arity[op]==2) {b.right=static_cast<Half>(t.n);t.cell[t.n++]={0,0,static_cast<Half>(remaining-left),0};}
    }
}
AX_FN bool trace(const Tree &t,const Convention &v,Train<utterance> &out) {
    Half stack[2*branches];Word top=1;stack[0]=0;
    while (top) {
        Word e=stack[--top],j=e&32767;const auto &node=t.cell[j];
        if (e&32768 || node.type<actions) {utter(out,v.name[node.type]);continue;}
        if (v.backwards) stack[top++]=static_cast<Half>(32768+j);
        else utter(out,v.name[node.type]);
        if (node.right) stack[top++]=node.right;
        stack[top++]=node.left;
    }return !out.full;
}
AX_FN bool predict(Tree &t,const Convention &v) {
    for (Word j=t.n;j>0;--j) {
        auto b=t.cell[j-1];Summary summary;
        if (b.type<actions) discharge(summary,signal(v.motor[b.type]));
        else {
            Word op=b.type-actions;
            for (Word k=0;k<v.length[op];++k) {
                Word code=v.law[op][k];
                if (code<call0) {if (summary.length==~0ull) return false;discharge(summary,signal(code));}
                else if (!combine(summary,t.meaning[code==call0 ? b.left : b.right])) return false;
            }
        }
        t.meaning[j-1]=summary;
    }
    return true;
}
AX_FN Byte physical_at(const Tree &t,const Convention &v,Count index) {
    Word j=0;
    while (t.cell[j].type>=actions) {
        auto node=t.cell[j];Word op=node.type-actions,next=~0u;
        for (Word i=0;i<v.length[op];++i) {
            Byte symbol=v.law[op][i];if (symbol<call0) {if (!index) return symbol;--index;continue;}
            Word other=symbol==call0 ? node.left : node.right;
            if (index<t.meaning[other].length) {next=other;break;}index-=t.meaning[other].length;
        }
        if (next==~0u) return 0;
        j=next;
    }
    return v.motor[t.cell[j].type];
}
struct Probes {
    Word paths=0,perfect=0,answered=0,performed=0,performed_ok=0,samples=0,samples_ok=0;
    Word trips=0,returned=0,absent=0,overflow=0,grammar=0,recursion=0,deepest=0,first_bad=~0u;
    Count longest=0;
};
AX_FN bool equals_wave(const Mind &m,Slice actual,Slice desired) {
    if (actual.n!=desired.n) return false;
    for (Word k=0;k<actual.n;++k) if (var(desired.p[k]) ? desired.p[k]!=actual.p[k] :
        (var(actual.p[k]) || m.ear.model[actual.p[k]]!=signal(desired.p[k]))) return false;
    return true;
}
// A structural certificate for all expressions generated by this teacher.
// Extra or overlapping productions invalidate the certificate.
AX_FN bool certify(const Mind &m,const Decoder &d,const Convention &v) {
    if (!d.direction || m.circuit.count!=actions+verbs+m.circuit.guard_n) return false;
    for (Word j=0;j<actions+verbs;++j) {
        Train<32> target,speech;
        if (j<actions) {utter(target,v.name[j]);speech.push(v.motor[j]);}
        else {
            Byte left=call0,right=call1;compose(target,v,j-actions,{&left,1},{&right,1});
            speech.add({v.law[j-actions],v.length[j-actions]});
        }
        Word hits=0;
        for (Word k=0;k<m.circuit.count;++k) if (!m.circuit.cell[k].raw && equals_wave(m,cue(m.circuit,k),target.span()) &&
            equals_wave(m,output(m.circuit,k),speech.span())) ++hits;
        if (hits!=1) return false;
    }
    return true;
}
AX_FN bool certify(const Mind &m,const Convention &v,const RouteLaw &law) {
    if (m.recursion.n!=1) return false;
    auto &r=m.recursion.state[0];
    if (r.n!=actions || r.tail || r.center || !equals_wave(m,{r.prefix,r.head},{law.label.bytes,law.label.size})) return false;
    for (Word a=0;a<actions;++a) {
        Word j=0;for (;j<r.n;++j) if (equals_wave(m,token(r,j),{v.name[a].bytes,v.name[a].size})) break;
        if (j==r.n) return false;
        auto z=r.arm[j];const auto *y=r.wire+z.at+z.n;
        if (z.m!=2 || z.cuts!=2 || m.ear.model[y[0]]!=signal(law.go[a]) || m.ear.model[y[1]]!=signal(law.back[a])) return false;
    }
    return true;
}
AX_FN void examine(Mind &m,const Decoder &d,const Convention &v,const RouteLaw &law,Word key,Word probes,Word depth,
                   Word noise,procedure::Tissue &t,Probes &score) {
    score={};score.grammar=certify(m,d,v);score.recursion=certify(m,v,law);
    for (Word q=0;q<probes;++q) {
        Word weather=mix(key+q*0x85ebca6bu),parts=1+weather%depth;Tree truth;Train<utterance> uttered;
        grow(truth,v,weather,parts,q%3);if (!predict(truth,v) || !trace(truth,v,uttered)) {++score.overflow;continue;}
        ++score.paths;bool sensed=true;
        for (Word k=0;k<uttered.n;++k) {
            auto wave=distort(signal(uttered.bytes[k]),weather,noise);
            Word id=percept(m.ear,wave,m.genes,false);if (!id) sensed=false;uttered.bytes[k]=static_cast<Byte>(id);
        }
        Report response;Word root=0;
        if (sensed && (d.direction || uttered.n<=64)) root=read(m,d,t,uttered.span(),response);
        score.answered+=bool(root);Count len=truth.meaning[0].length;
        if (len>score.longest) score.longest=len;
        bool correct=root && response.voice.length==len && response.voice.hash==truth.meaning[0].hash;
        if (response.depth>score.deepest) score.deepest=response.depth;
        Word checks=len<65 ? Word(len) : 16;
        for (Word j=0;j<checks;++j) {
            Count where=len<65 ? j : j==0 ? 0 : j==1 ? len-1 : ((Count(mix(weather+j))<<32)|mix(weather+127*j))%len;
            ++score.samples;
            bool equal=root && m.ear.model[sound_at(m,d,t,uttered.span(),root,where)]==signal(physical_at(truth,v,where));
            score.samples_ok+=equal;correct&=equal;
        }
        if (len<65) {++score.performed;score.performed_ok+=correct;}
        score.perfect+=correct;if (!correct && score.first_bad==~0u) score.first_bad=q;
        Train<utterance> x,y;Byte moves[96];Word length=1+(mix(weather+9)%96);
        for (Word j=0;j<length;++j) moves[j]=static_cast<Byte>(mix(weather+j*0x6ab9143du)%actions);
        route_example(v,law,moves,length,x,y);sensed=true;
        for (Word j=0;j<x.n;++j) {Word id=percept(m.ear,distort(signal(x.bytes[j]),weather,noise),m.genes,false);sensed&=bool(id);x.bytes[j]=static_cast<Byte>(id);}
        Count result[192];Report r;
        if (sensed) for (Word j=0;j<m.recursion.n;++j) if (domain(m.recursion.state[j],x.span())) {r=recurrence(m.ear,m.recursion.state[j],x.span(),0,192,result);break;}
        bool good=r.status==recognized && r.spoken==y.n;
        for (Word j=0;j<y.n && good;++j) good=result[j]==signal(y.bytes[j]);
        ++score.trips;score.returned+=good;score.absent+=r.status==ambiguous;
    }
}
